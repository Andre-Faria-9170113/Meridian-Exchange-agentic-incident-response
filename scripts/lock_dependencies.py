"""Snapshot the installed dependency closure on the documented Python version.

Run after deliberately updating/resolving project dependencies. This is not a
resolver: missing/incompatible packages fail instead of inventing a lock.
"""
from importlib.metadata import distribution
from pathlib import Path
import platform

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
SEEDS = ["pydantic-ai-slim[openai]==2.54.0", "fastmcp-slim[server]==4.1.3",
         "pydantic>=2,<3", "python-dotenv>=1,<2", "pyyaml>=6,<7", "pytest>=8,<10", "packaging>=24"]


def main():
    pending = [Requirement(value) for value in SEEDS]
    selected, processed = {}, set()
    while pending:
        requirement = pending.pop()
        package = distribution(requirement.name)
        if package.version not in requirement.specifier:
            raise RuntimeError(f"Installed {requirement.name}=={package.version} violates {requirement}")
        name = canonicalize_name(requirement.name)
        selected[name] = package.version
        for extra in {"", *requirement.extras}:
            key = (name, extra)
            if key in processed:
                continue
            processed.add(key)
            environment = {**default_environment(), "extra": extra}
            for dependency in package.requires or []:
                parsed = Requirement(dependency)
                if parsed.marker is None or parsed.marker.evaluate(environment):
                    pending.append(parsed)
    content = "# Installed dependency closure; generated by scripts/lock_dependencies.py\n"
    content += f"# Verified on Python {platform.python_version()}, {platform.system()}; see README for scope.\n"
    content += "\n".join(f"{name}=={version}" for name, version in sorted(selected.items())) + "\n"
    (ROOT / "requirements.lock").write_text(content, encoding="utf-8")
    print(f"Locked {len(selected)} distributions")


if __name__ == "__main__":
    main()
